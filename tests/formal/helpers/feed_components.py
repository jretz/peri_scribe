@dataclasses.dataclass(frozen=True, kw_only=True)
class Collection:
    """Retain the complete policy-visible projection of one joined collection."""

    snapshots: frozenset[int]
    fatal: bool
    source_error: bool


@dataclasses.dataclass(frozen=True, kw_only=True)
class FeedValue:
    """Keep feed-order results immutable and independent of a replay's root path."""

    path: str | None
    changed: bool
    error: str | None


@dataclasses.dataclass(frozen=True, kw_only=True)
class Failure:
    """Retain exception type, message, and nesting without mutable tracebacks."""

    message: str
    children: tuple[Failure, ...] = ()

    @classmethod
    def capture(cls, error: Exception) -> Failure:
        """Admit exactly the native errors generated by the collection fixture.

        Returns:
            Immutable data sufficient to reconstruct the original exception tree.
        """
        if type(error) is ExceptionGroup:
            return cls(
                message=error.message,
                children=tuple(cls.capture(child) for child in error.exceptions),
            )
        assert type(error) is RuntimeError
        assert len(error.args) == 1
        assert isinstance(error.args[0], str)
        return cls(message=error.args[0])

    def exception(self) -> Exception:
        """Construct a fresh exception tree for one independent policy invocation.

        Returns:
            A new native exception with the captured type, arguments and children.
        """
        if self.children:
            return ExceptionGroup(
                self.message,
                tuple(child.exception() for child in self.children),
            )
        return RuntimeError(self.message)


@dataclasses.dataclass(frozen=True, kw_only=True)
class Receipt:
    """Share actual joined values and saved bytes within this conformance call."""

    kinds: tuple[str, ...]
    full: bool
    values: tuple[FeedValue, ...]
    failure: Failure | None
    snapshots: frozenset[int]

    def collection(self) -> Collection:
        """Project the captured native result without recomputing worker behavior.

        Returns:
            The result consumed by the checked post-collection policy.
        """
        return Collection(
            snapshots=self.snapshots,
            fatal=self.failure is not None,
            source_error=any(value.error for value in self.values),
        )


def check_delegate(
    fetch: collections.abc.Callable[
        [peri_scribe.sources.feed_types.Feed],
        peri_scribe.sources.fetching.FeedOutcome,
    ],
    probe: tests.formal.helpers.feed_coordinator.CollectionProbe,
) -> None:
    """Check actual facade argument wiring before returning any shared result."""
    assert isinstance(fetch, functools.partial)
    assert fetch.func == probe.fetch
    assert fetch.args == ()
    assert fetch.keywords == {
        "base_dir": probe.directory.parents[1],
        "year": 2026,
        "full": probe.case.full,
    }
    state = peri_scribe.pipeline_state.read_state(probe.directory)
    deferred = peri_scribe.pipeline_state.has_deferred_inputs(probe.directory)
    if probe.case.deferred:
        assert deferred, "Collection began before deferred intent was recorded"
        remaining = (
            (peri_scribe.pipeline_stages.Stage.REPORTS,) if probe.case.prior else ()
        )
    else:
        assert not deferred
        remaining = peri_scribe.pipeline_state.DERIVED_STAGES
    if probe.case.full:
        remaining = peri_scribe.pipeline_state.DERIVED_STAGES
    assert state == peri_scribe.pipeline_state.PendingRun(
        remaining=remaining,
        unconditional=probe.case.full,
    ), "Collection began before the exact recovery intent was recorded"


@dataclasses.dataclass(kw_only=True)
class NativeProbe(tests.formal.helpers.feed_coordinator.CollectionProbe):
    """Capture only the real collector return or raised exception after native join."""

    values: tuple[FeedValue, ...] = ()
    failure: Failure | None = None
    collected: int = 0

    @typing.override
    def install(self, patch: pytest.MonkeyPatch) -> None:
        """Observe the extraction seam while leaving the entire native path active."""
        super().install(patch)
        original = peri_scribe.sources.fetching.collect_feed_outcomes

        def collect(
            fetch: collections.abc.Callable[
                [peri_scribe.sources.feed_types.Feed],
                peri_scribe.sources.fetching.FeedOutcome,
            ],
        ) -> tuple[peri_scribe.sources.fetching.FeedOutcome, ...]:
            """Capture the immutable result after the actual runner has shut down.

            Returns:
                The unmodified actual native collector result.
            """
            check_delegate(fetch, self)
            self.collected += 1
            try:
                outcomes = original(fetch)
            except ExceptionGroup as error:
                self.failure = Failure.capture(error)
                raise
            self.values = tuple(
                FeedValue(
                    path=value.path.relative_to(self.directory).as_posix()
                    if value.path is not None
                    else None,
                    changed=value.changed,
                    error=value.error,
                )
                for value in outcomes
            )
            return outcomes

        patch.setattr(peri_scribe.sources.fetching, "collect_feed_outcomes", collect)

    def receipt(self) -> Receipt:
        """Publish complete evidence only after the native probe has passed.

        Returns:
            The exact immutable input to subsequent independent policy invocations.
        """
        assert self.collected == 1
        for identifier in self.saved:
            assert (self.directory / "sources" / f"{identifier}.gpkg").read_bytes() == (
                b"complete saved snapshot"
            )
        return Receipt(
            kinds=self.case.kinds,
            full=self.case.full,
            values=self.values,
            failure=self.failure,
            snapshots=frozenset(self.saved),
        )


@dataclasses.dataclass(kw_only=True)
class PolicyProbe(tests.formal.helpers.feed_coordinator.CollectionProbe):
    """Run the actual facade with independent marker bytes and an immutable join."""

    receipt: Receipt
    memory: tests.formal.helpers.pipeline_replay_files.Memory = dataclasses.field(
        init=False,
    )
    collected: int = 0
    cadence: datetime.datetime | None = None

    def __post_init__(self) -> None:
        """Allocate only a private branch head; entry values remain immutable."""
        self.memory = tests.formal.helpers.pipeline_replay_files.Memory(
            directory=self.directory,
            effects={},
        )

    @typing.override
    def prepare(self) -> None:
        """Use the production codec to establish this policy's exact initial state."""
        if self.case.prior:
            peri_scribe.pipeline_state.require_stages(
                self.directory,
                (peri_scribe.pipeline_stages.Stage.REPORTS,),
            )

    def collect(
        self,
        fetch: collections.abc.Callable[
            [peri_scribe.sources.feed_types.Feed],
            peri_scribe.sources.fetching.FeedOutcome,
        ],
    ) -> tuple[peri_scribe.sources.fetching.FeedOutcome, ...]:
        """Exercise actual delegation for every policy tuple before supplying input.

        Returns:
            Feed-order values relocated into this invocation's lexical namespace.
        """
        check_delegate(fetch, self)
        assert (self.case.kinds, self.case.full) == (
            self.receipt.kinds,
            self.receipt.full,
        )
        self.collected += 1
        self.saved.update(self.receipt.snapshots)
        if self.receipt.failure is not None:
            raise self.receipt.failure.exception()
        return tuple(
            peri_scribe.sources.fetching.FeedOutcome(
                path=self.directory / value.path if value.path is not None else None,
                changed=value.changed,
                error=value.error,
            )
            for value in self.receipt.values
        )

    @typing.override
    def install(self, patch: pytest.MonkeyPatch) -> None:
        """Keep all production policy functions and only replace the collection cut."""
        super().install(patch)
        patch.setattr(
            peri_scribe.sources.fetching,
            "collect_feed_outcomes",
            self.collect,
        )

    @typing.override
    def check_collection(self) -> None:
        """Require exactly one cut; native probes separately own worker observations."""
        assert self.collected == 1
        assert self.saved == self.receipt.snapshots
        assert not self.active
        assert not self.started
        assert not self.finished

    @typing.override
    def index(self, directory: pathlib.Path) -> None:
        """Check that the actual index delegation follows a successful join."""
        assert self.collected == 1
        assert self.receipt.failure is None
        super().index(directory)

    @typing.override
    def pending(self) -> bool:
        """Read current branch bytes through the actual production marker validator.

        Returns:
            The current pending or deferred requirement.
        """
        return bool(
            peri_scribe.pipeline_state.read_state(self.directory).remaining
            or peri_scribe.pipeline_state.has_deferred_inputs(self.directory),
        )

    @typing.override
    def acknowledged(self) -> bool:
        """Observe whether this invocation reached the real cadence delegation.

        Returns:
            Whether the production caller acknowledged successful full collection.
        """
        return self.cadence is not None

    def read_cadence(
        self,
        path: pathlib.Path,
    ) -> peri_scribe.sources.full_fetch_state.FullFetchState | None:
        """Supply the absent cadence input used by every original coordinator case.

        Returns:
            The original missing-checkpoint input for the production cadence policy.
        """
        assert path == peri_scribe.sources.full_fetch_state.state_path(self.directory)
        assert self.case.full
        assert self.collected == 0
        assert self.cadence is None
        return None

    def write_cadence(
        self,
        path: pathlib.Path,
        *,
        last_full_fetch: datetime.datetime,
    ) -> None:
        """Check the actual timestamp, destination and successful index precondition."""
        assert path == peri_scribe.sources.full_fetch_state.state_path(self.directory)
        assert last_full_fetch.tzinfo is datetime.UTC
        assert self.case.full
        assert not self.case.deferred
        assert self.attempted
        assert not self.case.index_failure
        assert self.collected == 1
        assert self.receipt.failure is None
        assert not any(value.error for value in self.receipt.values)
        assert self.cadence is None
        self.cadence = last_full_fetch

    @typing.override
    def run(self) -> tests.formal.helpers.feed_coordinator.Outcome:
        """Scope private byte effects and cadence delegation to one actual invocation.

        Returns:
            Independently observed production policy output.
        """
        with pytest.MonkeyPatch.context() as patch:
            patch.setattr(peri_scribe.durable_file, "at", self.memory.at)
            patch.setattr(
                peri_scribe.sources.full_fetch_state,
                "read_state",
                self.read_cadence,
            )
            patch.setattr(
                peri_scribe.sources.full_fetch_state,
                "write_state",
                self.write_cadence,
            )
            return super().run()


def mask(values: frozenset[int]) -> int:
    """Encode feed identifiers in the independent Lean transport basis.

    Returns:
        The exact finite bitset.
    """
    return sum(1 << (value - 1) for value in values)


def lean_outcome(row: tuple[int, ...]) -> tests.formal.helpers.feed_coordinator.Outcome:
    """Read the compiled projection without implementing its policy in Python.

    Returns:
        The six fields observed by the original coordinator assertions.
    """
    snapshots, indexed, pending, acknowledged, attempted, failed = row
    return tests.formal.helpers.feed_coordinator.Outcome(
        snapshots=frozenset(
            number for number in range(1, 4) if snapshots >> (number - 1) & 1
        ),
        indexed=frozenset(
            number for number in range(1, 4) if indexed >> (number - 1) & 1
        ),
        pending=bool(pending),
        acknowledged=bool(acknowledged),
        attempted=bool(attempted),
        phase="failed" if failed else "done",
    )


def check_projection(
    states: collections.abc.Iterable[dict[str, str]],
    checked: collections.abc.Mapping[
        tests.formal.helpers.feed_coordinator.Case,
        collections.abc.Set[tests.formal.helpers.feed_coordinator.Outcome],
    ],
) -> dict[tuple[tuple[str, ...], bool], frozenset[Collection]] | None:
    """Compare every TLC terminal set with the image of its actual collection cuts.

    Returns:
        Checked independent cuts, or absence without a current proof build.
    """
    if not tests.formal.helpers.feed_component_binding.proof_current():
        return None
    cuts: dict[tests.formal.helpers.feed_coordinator.Case, set[Collection]] = {}
    for state in states:
        results = tuple(re.findall(r'"([^\"]+)"', state["result"]))
        fatal = "fatal" in results
        if state["phase"] != '"index"' and not (state["phase"] == '"failed"' and fatal):
            continue
        case = tests.formal.helpers.feed_coordinator.Case(
            kinds=tuple(re.findall(r'"([^\"]+)"', state["kind"])),
            full=state["full"] == "TRUE",
            prior=state["prior"] == "TRUE",
            index_failure=state["indexFailure"] == "TRUE",
            deferred=state["deferIndex"] == "TRUE",
        )
        cuts.setdefault(case, set()).add(
            Collection(
                snapshots=tests.formal.helpers.feed_coordinator.integer_set(
                    state["snapshots"],
                ),
                fatal=fatal,
                source_error=not fatal and "sourceError" in results,
            ),
        )
    assert cuts.keys() == checked.keys()
    shared: dict[tuple[tuple[str, ...], bool], frozenset[Collection]] = {}
    requests = []
    owners = []
    for case, collection_cuts in cuts.items():
        key = (case.kinds, case.full)
        frozen = frozenset(collection_cuts)
        assert shared.setdefault(key, frozen) == frozen, case
        for collection in collection_cuts:
            requests.append(
                "feed-policy "
                + " ".join(
                    map(
                        str,
                        (
                            int(case.full),
                            int(case.prior),
                            int(case.index_failure),
                            int(case.deferred),
                            mask(collection.snapshots),
                            int(collection.fatal),
                            int(collection.source_error),
                        ),
                    ),
                ),
            )
            owners.append(case)
    projected: dict[
        tests.formal.helpers.feed_coordinator.Case,
        set[tests.formal.helpers.feed_coordinator.Outcome],
    ] = {}
    for case, row in zip(
        owners,
        tests.formal.helpers.oracle.evaluate(requests),
        strict=True,
    ):
        projected.setdefault(case, set()).add(lean_outcome(row))
    assert projected == checked
    return shared


@dataclasses.dataclass(frozen=True, kw_only=True)
class Counts:
    """Keep exhaustive policy coverage separate from the native concurrency basis."""

    policies: int
    native: int
    coupled: int = 0


def replay(
    checked: collections.abc.Mapping[
        tests.formal.helpers.feed_coordinator.Case,
        collections.abc.Set[tests.formal.helpers.feed_coordinator.Outcome],
    ],
    cuts: collections.abc.Mapping[tuple[tuple[str, ...], bool], frozenset[Collection]]
    | None,
    directory: pathlib.Path,
) -> Counts:
    """Run independent native workers once per input and every real policy invocation.

    Returns:
        Exact actual concurrency and policy execution counts, including full fallback.
    """
    if cuts is None:
        count = tests.formal.helpers.feed_coordinator.replay(checked, directory)
        return Counts(policies=count, native=count)
    if not tests.formal.helpers.feed_component_binding.supported():
        count = tests.formal.helpers.feed_coordinator.replay(checked, directory)
        return Counts(policies=count, native=count)
    receipts: dict[tuple[tuple[str, ...], bool], Receipt] = {}
    for number, key in enumerate(cuts):
        kinds, full = key
        case = tests.formal.helpers.feed_coordinator.Case(
            kinds=kinds,
            full=full,
            prior=False,
            index_failure=False,
            deferred=False,
        )
        probe = NativeProbe(
            case=case,
            directory=directory / "native" / str(number) / "data" / "2026",
        )
        assert probe.run() in checked[case]
        receipt = probe.receipt()
        assert receipt.collection() in cuts[key]
        receipts[key] = receipt
    coupled = 0
    for case, expected in checked.items():
        if case.kinds not in {
            ("same", "same", "same"),
            ("change", "same", "same"),
            ("sourceError", "change", "same"),
        } or not (case.prior or case.index_failure or case.deferred):
            continue
        probe = NativeProbe(
            case=case,
            directory=directory / "coupled" / str(coupled) / "data" / "2026",
        )
        assert probe.run() in expected
        assert probe.receipt().collection() in cuts[case.kinds, case.full]
        coupled += 1
    for number, (case, expected) in enumerate(checked.items()):
        probe = PolicyProbe(
            case=case,
            directory=directory / "policy" / str(number) / "data" / "2026",
            receipt=receipts[case.kinds, case.full],
        )
        observed = probe.run()
        assert observed in expected, (case, observed, expected)
    return Counts(policies=len(checked), native=len(receipts), coupled=coupled)
